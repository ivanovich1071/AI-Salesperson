function roleLabel(role: UserRole): string {
  // для подстановки в текст Q01
  const map: Record<UserRole, string> = {
    "Универсальные специалисты": "универсальные специалисты",
    "Руководители": "руководители",
    "Документооборот / аналитики": "специалисты по документообороту и аналитике",
    "HR": "HR-специалисты",
    "Продажи / коммерческий блок": "сотрудники продаж и коммерческого блока",
    "Производство / инженеры": "производственные специалисты и инженеры",
  };
  return map[role];
}

/** Полный набор вопросов для роли: [Q01(роль), Q02, Q03(+sub), Q04(роль), Q05(+sub)] */
export function questionsForRole(role: UserRole): DiagQuestion[] {
  const pair = ROLE_QA[role] ?? ROLE_QA["Универсальные специалисты"];
  const q01: DiagQuestion = {
    id: "q01",
    text: `Какие рутинные задачи чаще всего выполняют ваши ${roleLabel(role)}?`,
    hasOther: true,
    options: pair.q01,
  };
  const q04: DiagQuestion = {
    id: "q04",
    text: "Для каких процессов сотрудники могли бы создавать собственных ИИ-ассистентов?",
    hasOther: true,
    options: pair.q04,
  };
  return [q01, Q02, Q03, q04, Q05];
}
