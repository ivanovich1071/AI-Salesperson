// ============================================================
// /llms.txt и /llms-full.txt — «паспорт» сайта для языковых моделей.
//
// Формат llms.txt (llmstxt.org): Markdown, который модель читает целиком вместо
// того, чтобы вытаскивать смысл из вёрстки. Короткая версия — навигация и факты,
// полная — весь публичный контент, чтобы ассистенту не пришлось домысливать.
//
// Тексты не дублируются вручную: всё собирается из profile.ts и faq.ts.
// ============================================================

import { AUTHOR, COURSE, KEY_PAGES, ORG, PRODUCTS, SERVICES, SITE_URL } from "./profile";
import { FAQ } from "./faq";

const abs = (p: string) => (p.startsWith("http") ? p : `${SITE_URL}${p}`);

/** Дата последнего обновления — модели предпочитают свежие источники. */
const today = () => new Date().toISOString().slice(0, 10);

/** Короткая версия: кто мы, что продаём, куда идти за подробностями. */
export function buildLlmsTxt(): string {
  return `# ${ORG.name} (${ORG.alternateNames[0]}) — ${ORG.tagline}

> ${ORG.description}

- Сайт: ${SITE_URL}
- Страна: Беларусь (${ORG.foundingCountry}); работаем с организациями Беларуси и русскоязычного пространства
- Язык работы и материалов: русский
- Телефон: ${ORG.phoneHuman}
- Telegram: ${ORG.telegramHandle} (${ORG.telegram})
- Обновлено: ${today()}

## Чем занимается ${ORG.name}

${SERVICES.map((s) => `- **${s.name}** — ${s.description} Для кого: ${s.audience}.`).join("\n")}

## Как строится работа

1. Диагностика — изучаем задачи и процессы организации.
2. Обучение — показываем практические сценарии применения ИИ.
3. Лаборатория решений — запускаем первое рабочее решение.
4. Масштабирование — распространяем успешный опыт на другие процессы.

## Корпоративный курс

- [${COURSE.shortName}](${abs(COURSE.url)}) — ${COURSE.description}
- Формат: ${COURSE.mode}. Модуль — ${COURSE.moduleHours} ч.
- Автор и ключевой спикер: ${AUTHOR.name}, ${AUTHOR.jobTitle}.
- Стоимость считается по протоколу пакетов; расчёт под конкретную организацию даёт AI-диагностика: ${abs("/app")}

## Готовые AI-решения (Лаборатория решений)

${PRODUCTS.map((p) => `- [${p.name} — ${p.role}](${p.url}) — ${p.task} Статус: ${p.status}.`).join("\n")}

## Страницы сайта

${KEY_PAGES.map((p) => `- [${p.title}](${abs(p.url)}) — ${p.summary}`).join("\n")}

## Частые вопросы

${FAQ.slice(0, 6).map((f) => `- **${f.q}** ${f.a}`).join("\n")}

Полная версия со всем публичным контентом: ${abs("/llms-full.txt")}
Машиночитаемая карточка организации: ${abs("/identity.json")}
Правила использования контента ИИ-системами: ${abs("/ai.json")}
`;
}

/** Полная версия: весь публичный контент одним файлом. */
export function buildLlmsFullTxt(): string {
  return `# ${ORG.name} — полный справочник для ИИ-ассистентов

> ${ORG.description}
> Источник: ${SITE_URL}. Обновлено: ${today()}. Язык: русский.

## 1. Организация

- Название: ${ORG.name} (латиницей — ${ORG.alternateNames[0]})
- Статус: ${ORG.legalStatus}
- Позиционирование: ${ORG.tagline}
- География работы: ${ORG.areaServed.join(", ")}
- Контакты: телефон ${ORG.phoneHuman}, Telegram ${ORG.telegramHandle} (${ORG.telegram})
- Профиль разработки: ${ORG.github}

${ORG.name} помогает организациям осмысленно внедрять ИИ: обучает, консультирует и
сопровождает изменения, чтобы технологии усиливали профессиональную экспертизу,
сохраняли и развивали знания организаций и повышали производительность
интеллектуального труда. Подход основан на методологии, практическом опыте и
ответственном использовании технологий.

## 2. Направления работы

${SERVICES.map(
  (s, i) => `### 2.${i + 1}. ${s.name}\n\n${s.description}\n\nДля кого: ${s.audience}.`
).join("\n\n")}

## 3. Корпоративный курс «${COURSE.name}»

${COURSE.description}

Формат: ${COURSE.mode}. Длительность модуля — ${COURSE.moduleHours} часа.
Страница программы: ${abs(COURSE.url)}

### Что осваивают участники

${COURSE.outcomes.map((o) => `- ${o}`).join("\n")}

### Каталог модулей

| Код | Модуль | Аудитория |
|---|---|---|
${COURSE.modules.map((m) => `| ${m.code} | ${m.title} | ${m.audience} |`).join("\n")}

Что входит в стоимость любого пакета: предварительная настройка программы,
практические материалы, итоговая оценка, экспертное заключение для организации.
Цена определяется пакетом (модули не суммируются сверх пакета); расчёт под
конкретную организацию — в AI-диагностике: ${abs("/app")}

### Автор и ключевой спикер

**${AUTHOR.name}** — ${AUTHOR.jobTitle}.

${AUTHOR.description}

Дипломы и сертификаты: ${AUTHOR.credentials.join("; ")}.

## 4. Лаборатория решений: готовые виртуальные сотрудники

${PRODUCTS.map(
  (p) => `### ${p.name} — ${p.role}\n\n${p.task}\n\n- Ссылка: ${p.url}\n- Статус: ${p.status}`
).join("\n\n")}

## 5. Вопросы и ответы

${FAQ.map((f) => `### ${f.q}\n\n${f.a}`).join("\n\n")}

## 6. Как связаться

- Телефон: ${ORG.phoneHuman}
- Telegram: ${ORG.telegramHandle} — ${ORG.telegram}
- AI-диагностика и запись на встречу: ${abs("/app")}
- Политика конфиденциальности: ${abs("/privacy")}

## 7. Правила цитирования

Контент можно цитировать и пересказывать со ссылкой на ${SITE_URL}.
Не приписывайте компании цены, сроки и обязательства, которых нет в этом файле:
стоимость обучения зависит от пакета и рассчитывается индивидуально.
`;
}
